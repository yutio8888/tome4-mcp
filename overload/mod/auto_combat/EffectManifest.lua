function M.entry(talent) return M.ENTRIES[talent] end
function M.supported(talent) return talent~=nil and M.ENTRIES[talent]~=nil end

-- Every distinct target-request sequence a movement adapter can resolve to. A
-- variant matrix has one sequence per executable branch; a static adapter has
-- exactly one. Used by the pure policy validator, which cannot read runtime
-- state and therefore accepts a plan that matches any declared branch.
function M.requestSequences(entry)
    local movement=entry and entry.movement
    if type(movement)~='table' then return {} end
    if movement.variants then
        local out={}
        for _,variant in ipairs(movement.variants) do
            if variant.movement and type(variant.movement.target_requests)=='table' then
                out[#out+1]=variant.movement.target_requests
            elseif variant.unsupported and type(variant.unsupported.requests)=='table' then
                -- A known but unimplemented branch still declares its request
                -- sequence, so a policy using the S2 shape validates statically
                -- and then gets the typed capability reason at plan time.
                for _,requests in ipairs(variant.unsupported.requests) do
                    out[#out+1]=requests
                end
            end
        end
        return out
    end
    if type(movement.target_requests)=='table' then return {movement.target_requests} end
    return {}
end
function M.isSustain(talent)
    local entry=M.ENTRIES[talent]
    return entry~=nil and entry.kind=='sustain'
end

-- Components that can affect an actor, in evaluation order (ground last).
function M.effectComponents(entry)
    local out={}
    for _,component in ipairs(entry and entry.components or {}) do
        if component.phase~='cursor' then out[#out+1]=component end
    end
    return out
end

-- Distinct conditional variants declared by an entry: `{when, components}`.
function M.variants(entry)
    local groups={}
    for _,component in ipairs(entry and entry.components or {}) do
        local key=component.when and (component.when.kind..':'..tostring(component.when.id or component.when.at_least or component.when.below)) or 'always'
        local group=groups[key]
        if not group then
            group={when=component.when or {kind='always'},components={}}
            groups[key]=group
            groups[#groups+1]=group
        end
        group.components[#group.components+1]=component
    end
    return groups
end

-- Public capability summary, derived from the canonical components so it can
-- never disagree with the guard's source of truth.
function M.summary()
    local talents={}
    for talent,entry in pairs(M.ENTRIES) do
        local compat=M.compat(entry)
        talents[#talents+1]={talent=talent,kind=entry.kind,target=entry.target,
            delivery=compat.delivery,shape=compat.shape,range=compat.range,radius=compat.radius,
            resource=entry.resource,selffire=compat.selffire,friendlyfire=compat.friendlyfire,
            friendlyfire_risk=compat.friendlyfire_risk,
            has_ground=compat.ground~=nil,has_secondary=compat.secondary~=nil}
    end
    table.sort(talents,function(a,b) return a.talent<b.talent end)
    return {schema=M.SCHEMA,adapter_version=M.VERSION,game_version=M.GAME_VERSION,
        source_schema=Sources.schema,unsupported=M.UNSUPPORTED,talents=talents}
end

-- Derived compatibility view: a conservative flattening of the canonical
-- components for capability reporting and validators. It is never the guard's
-- input. `M.compat(entry)` guarantees the summary and validators agree with
-- the components.
local SHAPE_ORDER={widebeam=6,cone=5,ball=4,beam=3,bolt=2,hit=1,melee=0}
function M.compat(entry)
    if not entry then return nil end
    local primary
    local shape,delivery,selffire,friendlyfire
    local ground,secondary
    for _,component in ipairs(entry.components or {}) do
        if component.phase=='ground' then ground=component end
        if component.phase=='secondary' then secondary=component end
        if component.phase=='instant' or component.phase=='projectile' or component.phase=='melee' then
            if not primary then primary=component end
            local order=SHAPE_ORDER[component.shape] or 0
            if not shape or order>(SHAPE_ORDER[shape] or 0) then shape=component.shape end
            if component.delivery=='projectile' then delivery='projectile'
            elseif component.delivery=='attackTarget' then delivery=delivery or 'attackTarget'
            elseif not delivery then delivery='project' end
            local sf=component.selffire
            if type(sf)=='table' then sf='unknown' end
            if sf~=nil and (selffire==nil or (tonumber(sf) or 100)>(tonumber(selffire) or 0)) then selffire=sf end
            local ff=component.friendlyfire
            if type(ff)=='table' then ff='unknown' end
            if ff~=nil and (friendlyfire==nil or (tonumber(ff) or 100)>(tonumber(friendlyfire) or 0)) then friendlyfire=ff end
        end
    end
    local risk='none'
    if selffire~=0 or friendlyfire~=0 then
        if shape=='beam' or shape=='bolt' or shape=='widebeam' then risk='line'
        elseif shape=='ball' or shape=='cone' then risk='area' end
    end
    return {shape=shape,delivery=delivery,range=entry.range,radius=entry.radius,
        selffire=selffire or 0,friendlyfire=friendlyfire or 0,friendlyfire_risk=risk,
        cursor=entry.cursor,ground=ground,secondary=secondary,union=entry.union,
        components=entry.components,primary=primary}
end


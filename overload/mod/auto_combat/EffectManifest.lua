function M.verify(policy)
    local errors={}
    -- Checklist A (BND-REV-01): `policy.rules`/`policy.sustains` are caller data;
    -- only a dense+closed list is iterated. A malformed list is a typed error at
    -- this ingress — never a truncated prefix silently verified as complete (a
    -- sparse `policy.rules` with a hidden tail rule used to pass verify whole).
    local rules,ruleCount=nil,0
    if type(policy)=='table' and policy.rules~=nil then
        local dense,count=Json.denseArray(policy.rules)
        if not dense then
            return nil,{{path='rules',code='invalid_rules',cause=count}}
        end
        rules,ruleCount=policy.rules,count
    end
    local sustains,sustainCount=nil,0
    if type(policy)=='table' and policy.sustains~=nil then
        local dense,count=Json.denseArray(policy.sustains)
        if not dense then
            return nil,{{path='sustains',code='invalid_sustains',cause=count}}
        end
        sustains,sustainCount=policy.sustains,count
    end
    for index=1,ruleCount do
        local rule=rules[index]
        local action=rule['then'] and rule['then'].action
        local path='rules['..index..']'
        if action~=nil and not M.ACTIONS[action] then
            errors[#errors+1]={path=path..'.then.action',code='unsupported_action'}
        end
        local entry=rule['then'] and rule['then'].talent and M.ENTRIES[rule['then'].talent] or nil
        if entry then
            local selector=rule['then'].target or (policy.targeting and policy.targeting.default)
            -- MFT-REV-03 (Option A): an actor step selector is the effective
            -- binding when the action/default selector is absent, so the
            -- self/hostile consistency check honours it.
            if selector==nil and type(rule['then'].target_plan)=='table' then
                -- Checklist A: the plan is caller-supplied policy data; only a
                -- dense/closed list has a trustworthy actor step (a sparse list
                -- must not resolve a selector out of its `ipairs` prefix).
                local dense,count=Json.denseArray(rule['then'].target_plan,1)
                if dense then
                    for index=1,count do
                        local step=rule['then'].target_plan[index]
                        if step.request=='actor' and step.selector~=nil then
                            selector=step.selector
                            break
                        end
                    end
                end
            end
            -- A no-target movement request (position/relative/native_random) needs
            -- no actor selector; the plugin must not invent a self requirement.
            local destination=rule['then'].destination
            local no_target_move=entry.kind=='movement' and type(destination)=='table'
                and (destination.selector=='position' or destination.selector=='relative'
                    or destination.selector=='native_random')
            if entry.target=='self' and selector~=nil and not M.SELF_SELECTORS[selector]
                and not no_target_move then
                errors[#errors+1]={path=path,code='selector_not_self_only',talent=rule['then'].talent}
            end
            if entry.target=='hostile' and selector~=nil and not M.HOSTILE_SELECTORS[selector]
                and not no_target_move then
                errors[#errors+1]={path=path,code='selector_not_hostile',talent=rule['then'].talent}
            end
            -- MFT-REV-03: an explicit ordered target plan must match the
            -- source-pinned movement adapter's request sequence exactly.
            local plan=rule['then'].target_plan
            local movement=entry.kind=='movement' and entry.movement or nil
            if type(plan)=='table' then
                -- Checklist A: the plan is caller-supplied, so validate it dense
                -- and closed BEFORE the `#`/index reads below. A malformed plan
                -- is `invalid_target_plan` (its own typed shape fault), never
                -- measured as a shorter complete plan.
                local dense,planCount=Json.denseArray(plan,1)
                if not dense then
                    errors[#errors+1]={path=path..'.then.target_plan',code='invalid_target_plan'}
                else
                    local sequences=M.requestSequences(entry)
                    if movement==nil or #sequences==0 then
                        errors[#errors+1]={path=path..'.then.target_plan',
                            code='target_plan_not_supported',talent=rule['then'].talent}
                    else
                        -- A variant matrix may declare several executable request
                        -- sequences; the static validator cannot read runtime state,
                        -- so a plan is valid when it matches any declared sequence
                        -- exactly (same length, same kinds, consistent selectors).
                        local matched=false
                        local selectorMismatch=nil
                        for _,expected in ipairs(sequences) do
                            local expectedDense,expectedCount=Json.denseArray(expected,1)
                            if expectedDense and planCount==expectedCount then
                                local stepOk=true
                                local mismatch=nil
                                for step=1,planCount do
                                    if plan[step].request~=expected[step] then stepOk=false break end
                                    if expected[step]=='actor' and plan[step].selector~=nil
                                        and selector~=nil and plan[step].selector~=selector then
                                        stepOk=false
                                        mismatch={path=path..'.then.target_plan['..step..'].selector',
                                            code='target_plan_selector_mismatch',
                                            expected=selector,got=plan[step].selector}
                                        break
                                    end
                                end
                                if stepOk then matched=true break end
                                if mismatch and selectorMismatch==nil then selectorMismatch=mismatch end
                            end
                        end
                        if not matched then
                            local expectedCount=#sequences==1
                                and select(2,Json.denseArray(sequences[1],1)) or nil
                            if selectorMismatch then
                                errors[#errors+1]=selectorMismatch
                            elseif expectedCount and planCount~=expectedCount then
                                errors[#errors+1]={path=path..'.then.target_plan',
                                    code='target_plan_mismatch',
                                    expected=table.concat(sequences[1],','),got=planCount}
                            else
                                errors[#errors+1]={path=path..'.then.target_plan',
                                    code='target_plan_mismatch',
                                    expected=#sequences==1 and table.concat(sequences[1],',')
                                        or 'one_of_declared_variants'}
                            end
                        end
                    end
                end
            end
        elseif rule['then'] and rule['then'].action=='use_talent' then
            errors[#errors+1]={path=path,code='unsupported_talent',talent=rule['then'].talent}
        end
    end
    for index=1,sustainCount do
        local sustain=sustains[index]
        if not M.isSustain(sustain.talent) then
            errors[#errors+1]={path='sustains['..index..']',code='not_a_sustain',talent=sustain.talent}
        end
    end
    if #errors==0 then return true end
    return nil,errors
end

return M
